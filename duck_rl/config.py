"""全部可调参数。

**原则：这里只写"我做的选择"，不抄模型里已有的事实。**
- 该放这里：时间尺度、动作缩放、奖励权重、指令范围、终止阈值
- 不该放这里：kp / kv / ctrlrange / 关节限位 / 初始姿态 / 质量
  —— 这些从 MjModel 读（见 scripts/check_model.py 打印出来的那些数）。
  抄进 config 就制造了第二份事实，早晚不一致，而不一致时的 bug 最难查。

调参顺序建议：先只改奖励权重（第 5 组），其它组基本不用动。
"""
# ml_collections 是 Google 的配置库；config_dict 是它的子模块，ConfigDict 类在这个模块里。
# ConfigDict() 造一个「能用点号访问的字典」：c.sim_dt = 0.002 比 c["sim_dt"] 好写，
# 支持嵌套，还能 .lock() —— 锁定后字段名写错会立刻报错，而不是静默多出一个没用的键。
from ml_collections import config_dict


# 返回一个新配置对象（不写成模块级常量，是为了让每个 env 各拿一份，互不影响）。
# 箭头 -> 只是类型提示，运行时不检查，作用是让 IDE 给补全。
def default_config() -> config_dict.ConfigDict:
    c = config_dict.ConfigDict()        # 空的配置容器，下面逐项填

    # ================================================================
    # 1. 时间尺度
    # 决定"策略多久做一次决定"。改它等于换了任务难度，不要边训边改。
    # ================================================================
    c.sim_dt = 0.002        # 物理步长 0.002 s = 500 Hz（MJCF 里也是这个值）
    c.ctrl_dt = 0.02        # 策略周期 0.02 s = 50 Hz → 每步内部跑 10 个物理子步
    c.episode_length = 1000 # 20 秒。太短学不会周期步态，太长浪费算力

    # ================================================================
    # 2. 动作
    # ctrl = 默认姿态 + action * action_scale，然后按 ctrlrange 剪裁
    # ================================================================
    # action_scale 决定"网络输出 ±1 时关节偏离默认姿态多少弧度"。
    #   0.1  → 太小，学不会抬腿（关节只在 6° 内打转）
    #   0.45 → 约 ±26°，够迈步（第 2 轮实验值）
    #   1.0  → 太大，一训练就抽风，容易摔
    # 【第 2 轮调整】0.3 → 0.45：第 1 轮策略"会站不会走"，怀疑腿摆不开。
    c.action_scale = 0.45

    # ================================================================
    # 3. 观测缩放
    # 网络对输入量纲敏感：角速度可能到 ±10 rad/s，关节速度可能到 ±20，
    # 缩放到 1 附近能让 PPO 的梯度更稳定。契约里只规定"顺序和维度"，
    # 缩放系数放这里，是因为它属于超参而不是结构。
    # ================================================================
    c.obs_scale_gyro = 0.25   # 角速度 ×0.25
    c.obs_scale_qd = 0.05     # 关节速度 ×0.05

    # ================================================================
    # 4. 速度指令范围（每个 episode 重置时随机采样）
    # 前进给足空间、后退给小空间：鸭子往前比往后容易得多。
    # ================================================================
    c.cmd_lin_x = (-0.4, 0.8)   # 前后 m/s，正 = 前进
    c.cmd_lin_y = (-0.3, 0.3)   # 左右 m/s，正 = 向左（MuJoCo 右手系）
    c.cmd_ang_z = (-0.8, 0.8)   # 转向 rad/s，正 = 左转

    # 采样策略。三维独立均匀采样有个盲区：[0, 0.3, 0]（纯侧移）的联合概率只有
    # 0.09%，4 万回合里才几十个样本 → 策略根本没学会侧移，实测会往后退。
    # 两个补偿措施，让"单轴指令"的样本量提上去：
    c.cmd_single_axis_prob = 0.3   # 30% 的回合只动一个轴，另两个强制为 0（手柄的实际用法）
    # 【第 5 轮调整】0.5 → 0.25：0.5 时策略被大量"大 vy 斜走"样本带偏，
    # 纯前进也走出了弧线（30 秒偏 62°）。降到 0.25 仍有约 1000 个侧移样本，够学。
    c.cmd_vy_edge_prob = 0.25      # vy 有 1/4 概率落在两侧边界 [±0.2, ±0.3]
    c.cmd_vy_edge_min = 0.2        # 上面那个区间的下限（绝对值）

    # ================================================================
    # 5. 奖励权重
    # 每项都是 0~1 的"满意度"，加权求和后就是单步奖励。
    # 参考量级：正常行走时单步 ≈ 4.3 分，其中：
    #   tracking_lin 2.5 + alive 0.3 + tracking_ang 0.8 + upright 0.5
    #   + height 0.5 ≈ 4.6，两项惩罚合计不到 0.001（只用来打破平局）
    #
    # ⚠ 最容易翻车的组合：w_alive 太大 + w_tracking_lin 太小
    #   → 策略发现"站着不动"每步稳拿 1.0+0.5+0.5，比冒险走更划算
    #   → 训练曲线漂亮、鸭子原地不动（新手必踩）
    # ================================================================
    # 【第 2 轮调整】第 1 轮坐实了这个坑：站着能拿 84% 的分，于是策略选择站。
    # 改法：压低"白给分"、抬高"走起来"的分。实测（指令 0.4）站着 ≈2.4、完美跟踪 ≈4.6，
    # 差距从 16% 拉到 88%，它才愿意冒险走。
    c.w_tracking_lin = 2.5    # 1.5 → 2.5：主目标，必须远大于辅助项
    c.w_tracking_ang = 0.8    # 【第 7 轮】0.4 → 0.8：转向全靠它（heading 在转向时被门控压低）
    c.w_upright = 0.5         # 躯干竖直：重力在机体系 z 轴投影接近 -1
    c.w_height = 0.5          # 高度维持：浮基 z 接近 height_ref
    c.w_alive = 0.3           # 1.0 → 0.3：白给分太大会让"站着不动"成为最优解
    c.w_action_rate = -0.01   # 动作平滑：惩罚相邻两帧动作的跳变（负权重 = 惩罚）
    c.w_torque = -0.0002      # 扭矩：惩罚 Στ²，让策略少用力

    # 【第 6 轮新增】航向跟踪。
    # tracking_ang 只看 gyro_z（此刻转多快），管不了"已经偏了多少"——实测策略每步
    # 角速度都接近 0、奖励满分，30 秒却累积偏了 60°。这一项直接比"当前偏航"和
    # "指令积分出来的期望航向"，偏 30° 就只有 0.07 分，逼它主动纠偏。
    #
    # 【第 7 轮修正】这一项把转向能力彻底压死了（实测 wz=0.15 只转 0.5°）。
    # 根因：训练早期转向必然不准，误差一超过 0.6 rad，exp(-e²/0.1) 就塌成 0，
    # 梯度也是 0——"转"这条路没有信号，而"不转"能保住 upright/height/alive
    # 的满分。PPO 于是落入"站住不动"的局部最优。
    # 修法：按指令分流。wz≈0 时本项全效（保住直线），wz 大时降到 15%（转向交回
    # tracking_ang，那是逐点有梯度的信号，exp4 证明它学得会 95%）。
    #
    # 【第 8 轮】sigma 0.2 → 0.1（回到 exp6 的值）。
    # exp7 证明转向不会再被这一项压死——因为转向时权重已被门控压到 0.12。
    # 而直行（wz=0、门控=1）时 0.8 + sigma 0.1 与 exp6 完全相同 → 直线应回到
    # exp6 的 1.6° 水平。即「exp6 的直线 + exp7 的转向」这个并集。
    c.w_heading = 0.8
    c.sigma_heading = 0.1     # 直行纠偏要狠；转向有门控兜着，不怕它太尖
    c.heading_gate_wz = 0.25  # 门控尺度：|wz| 到这个量级时 heading 权重减半
    c.heading_gate_floor = 0.15  # 转向时保留的最低比例（完全归零会让直线又漂）

    # 「高度维持」的参考高度。
    # 不是 keyframe 里的 0.15！实测：0.15 时脚底略插进地面约 1 cm，
    # 物理把它弹起后稳态是 0.1599~0.1600（已连续观察 100 s 以上稳定）。
    # 拿 0.15 当参考，策略一开局就被白扣分。
    c.height_ref = 0.16

    # 跟踪项里 exp(-误差²/σ) 的 σ（分母）。
    # 越小越"苛刻"：σ 小 → 误差稍大就得 0 分；σ 大 → 宽容但学不精。
    # 【第 2 轮调整】0.25 → 0.08：原来误差 0.4 m/s 只扣掉一半分（exp(-0.64)=0.53），
    # 对"站着不动"太宽容。收紧后同样误差只剩 0.007 分，逼它真去追速度。
    c.sigma_lin = 0.08
    c.sigma_ang = 0.25        # 转向误差容忍度，比线速度宽
    c.sigma_upright = 0.05    # 竖直项对姿态很敏感，所以给得很小
    c.sigma_height = 0.01     # 高度项更敏感：差 10 cm 就基本没分了

    # ================================================================
    # 6. 域随机化（第 9 轮引入）
    # 目的：把「仿真完美、真机就崩」这个 gap 提前暴露。
    # 现在所有成绩都是在摩擦固定 0.6、舵机无差异、质量分毫不差的理想环境里拿的，
    # 真机这三项全都会变。
    #
    # 实现见 `duck_rl/randomize.py`：只随机化 7 个小数组（不是整个 model），
    # 每环境一份，显存代价约 200 KB（实测训练峰值显存 2 GB，余量充足）。
    #
    # 范围依据：
    #   - 地面摩擦 0.3~1.0：瓷砖/木地板 0.3~0.5，橡胶垫 0.8~1.0
    #   - 舵机 kp ±20%：STS3215 个体差异实测能到这个量级
    #   - 关节摩擦 0.5~2.0 倍：齿轮批次差异 + 磨损
    #   - 质量 ±10%：打印件填充率差异 + 电池容量不同
    # ================================================================
    c.dr_enable = True             # 关掉可做 A/B 对照（训练脚本的 --no-dr）

    c.dr_friction = (0.3, 1.0)     # 地面滑动摩擦系数（基准 0.6）
    c.dr_frictionloss = (0.5, 2.0)  # 关节库仑摩擦倍数（基准 0.068 N·m）
    c.dr_armature = (0.8, 1.2)     # 转子惯量倍数（基准 0.027 kg·m²）
    c.dr_mass = (0.9, 1.1)         # 各 body 质量倍数（总质量 2.107 kg）
    c.dr_kp = (0.8, 1.2)           # 位置伺服刚度倍数（基准 13.37）
    c.dr_forcerange = (0.8, 1.2)   # 力矩上限倍数（基准 ±3.23 N·m）

    # ================================================================
    # 7. 终止条件
    # 摔倒不扣分，只是 done=True、本回合结束，之后没有奖励。
    # 策略是被"少赚"逼着学会不摔的，所以这里只需要给阈值。
    # ================================================================
    # 浮基高度低于它算摔。keyframe 初始高度是 0.15 m，
    # 给 0.10 意味着"蹲下去 5 cm 还允许，再低就算倒"。
    c.min_height = 0.10
    # 重力在机体系 z 轴的投影。竖直站立时 ≈ -1，躺平 ≈ 0，
    # 给 0.4 表示"比 -0.4 更正（即倾斜超过约 66°）算摔"。
    c.min_upright = 0.4

    return c                 # 整份配置交出去


if __name__ == "__main__":
    cfg = default_config()   # 造一份默认配置
    print("=== config ===")
    for k in cfg.keys():     # 打印全部字段，方便核对是否生效
        print(f"  {k:<20} {cfg[k]}")
